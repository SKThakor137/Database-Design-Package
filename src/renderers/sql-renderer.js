/**
 * Standard SQL DDL Renderer
 * Reconstructs normalized standard SQL CREATE TABLE statements with constraints and foreign keys.
 * Pure Node.js - Zero dependencies.
 */

class SQLRenderer {
    static generateSQL(schemaMap, options = {}) {
        const tables = Object.keys(schemaMap);
        let sql = `-- Generated by schemagraph\n-- Normalized SQL DDL Schema\n\n`;

        tables.forEach(tableName => {
            const table = schemaMap[tableName];
            sql += `CREATE TABLE ${tableName} (\n`;

            const colDefs = [];
            const pks = [];

            table.columns.forEach(col => {
                let def = `    ${col.name} ${SQLRenderer.mapToSqlType(col.type)}`;
                if (col.isPrimary) {
                    pks.push(col.name);
                }
                if (!col.isNullable) {
                    def += ' NOT NULL';
                }
                if (col.isUnique && !col.isPrimary) {
                    def += ' UNIQUE';
                }
                colDefs.push(def);
            });

            if (pks.length > 0) {
                colDefs.push(`    PRIMARY KEY (${pks.join(', ')})`);
            }

            // Foreign keys
            table.relations.forEach(rel => {
                const fromField = rel.from || rel.fromColumn;
                const toField = rel.toField || rel.toColumn || 'id';
                colDefs.push(`    FOREIGN KEY (${fromField}) REFERENCES ${rel.toTable}(${toField}) ON DELETE CASCADE`);
            });

            sql += colDefs.join(',\n') + '\n);\n\n';
        });

        return sql;
    }

    static mapToSqlType(type) {
        if (!type) return 'VARCHAR(255)';
        const t = type.toUpperCase();
        if (t.includes('INT')) return 'INTEGER';
        if (t.includes('UUID')) return 'UUID';
        if (t.includes('BOOL')) return 'BOOLEAN';
        if (t.includes('DATE') || t.includes('TIME')) return 'TIMESTAMP';
        if (t.includes('FLOAT') || t.includes('DECIMAL') || t.includes('NUMBER')) return 'NUMERIC(10,2)';
        if (t.includes('JSON')) return 'JSONB';
        if (t.includes('TEXT') || t.includes('STRING')) return 'VARCHAR(255)';
        return 'VARCHAR(255)';
    }
}

module.exports = SQLRenderer;
