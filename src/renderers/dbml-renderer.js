/**
 * DBML (Database Markup Language) Renderer
 * Generates standard DBML compatible with dbdiagram.io and dbdocs.io.
 * Pure Node.js - Zero dependencies.
 */

class DBMLRenderer {
    static generateDBML(schemaMap, options = {}) {
        const tables = Object.keys(schemaMap);
        let dbml = `// Generated by schemagraph\n// Use this DBML at https://dbdiagram.io/\n\n`;

        tables.forEach(tableName => {
            const table = schemaMap[tableName];
            dbml += `Table ${tableName} {\n`;

            table.columns.forEach(col => {
                const settings = [];
                if (col.isPrimary) settings.push('pk');
                if (col.isUnique) settings.push('unique');
                if (!col.isNullable) settings.push('not null');

                const settingsStr = settings.length > 0 ? ` [${settings.join(', ')}]` : '';
                dbml += `  ${col.name} ${col.type || 'varchar'}${settingsStr}\n`;
            });

            dbml += `}\n\n`;
        });

        // Add explicit references
        tables.forEach(tableName => {
            const table = schemaMap[tableName];
            table.relations.forEach(rel => {
                dbml += `Ref: ${tableName}.${rel.from} > ${rel.toTable}.${rel.toField}\n`;
            });
        });

        return dbml;
    }
}

module.exports = DBMLRenderer;
